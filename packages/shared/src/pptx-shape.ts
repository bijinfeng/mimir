const coordinate = z.number().int().min(-100000000).max(100000000)
export const pptxManualShapeSchema = z
  .object({
    kind: z.enum(PPTX_INSERT_SHAPE_KINDS),
    slide: z.number().int().nonnegative(),
    offset: z
      .object({
        x: coordinate,
        y: coordinate,
        cx: coordinate.nonnegative(),
        cy: coordinate.nonnegative(),
      })
      .strict(),
    flipH: z.boolean().optional(),
    flipV: z.boolean().optional(),
  })
  .strict()
  .superRefine((value, ctx) => {
    const line = ['line', 'lineArrow', 'lineArrowDouble', 'lineBent', 'lineCurved'].includes(
      value.kind,
    )
    if ((!line && (!value.offset.cx || !value.offset.cy)) || (!value.offset.cx && !value.offset.cy))
      ctx.addIssue({ code: 'custom', message: '形状须有可见尺寸' })
    if (!line && (value.flipH || value.flipV))
      ctx.addIssue({ code: 'custom', message: '仅连接线接受绘制方向' })
  })
export type PptxManualShape = z.infer<typeof pptxManualShapeSchema>
